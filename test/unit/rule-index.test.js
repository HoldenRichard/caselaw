/**
 * The rules index and trigger-scoped retrieval (0.5).
 *
 * A session used to open every file in active/ to read its Trigger: 7 to 9
 * rules cost 1,650 to 2,040 words, and `rules --for tests/test_x.py` found
 * nothing because it matched paths only. The index is one line per rule in
 * force, generated; a rule's own text is read only when its Trigger matches.
 */

import { test, describe, beforeEach, afterEach } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtemp, rm, mkdir, writeFile, readFile, stat } from 'node:fs/promises'
import { tmpdir } from 'node:os'
