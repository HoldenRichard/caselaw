const CLI = fileURLToPath(new URL('../../bin/cli.mjs', import.meta.url))
const cli = (args, { cwd, input = '' }) => new Promise((resolve) => {
  const child = spawn(process.execPath, [CLI, ...args], { cwd, env: { ...process.env, NO_COLOR: '1' }, stdio: ['pipe', 'pipe', 'pipe'] })
  let out = ''
  child.stdout.on('data', (d) => (out += d))
  child.stderr.on('data', (d) => (out += d))
  child.on('close', (code) => resolve({ code, out }))
  child.stdin.on('error', () => {})
  child.stdin.end(input)
})

let root
beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), 'caselaw-index-'))
  execFileSync('git', ['init', '-q'], { cwd: root })
  execFileSync('git', ['config', 'gc.auto', '0'], { cwd: root })
  execFileSync('git', ['config', 'user.email', 't@t'], { cwd: root })
  execFileSync('git', ['config', 'user.name', 't'], { cwd: root })
  execFileSync('git', ['config', 'commit.gpgsign', 'false'], { cwd: root })
})
afterEach(async () => { await rm(root, { recursive: true, force: true }) })

const put = async (rel, content) => { await mkdir(join(root, rel, '..'), { recursive: true }); await writeFile(join(root, rel), content, 'utf8') }
const read = (rel) => readFile(join(root, rel), 'utf8')
const exists = async (rel) => { try { await stat(join(root, rel)); return true } catch { return false } }
const rule = (name, trigger, { enforcement = 'memory', origin = '2026-01-01 an incident here' } = {}) =>
  `# ${name}\n\n**Trigger:** ${trigger}\n\n**Rule:** do the thing.\n\n**Origin:** ${origin}\n\n**Enforcement:** ${enforcement}\n`

describe('the generated index', () => {
  test('POSITIVE CONTROL: one line per active rule, sorted, with the gate id for machine enforcement; deterministic', async () => {
    await put('docs/rules/active/b-rule.md', rule('b-rule', 'editing a\n  migration file', { enforcement: 'machine:no-sweep' }))
    await put('docs/rules/active/a-rule.md', rule('a-rule', 'adding or changing a test.'))
    await syncRuleIndex(root)
    const text = await read('docs/rules/INDEX.md')
    const lines = text.split('\n').filter((l) => l.startsWith('- '))
    assert.deepEqual(lines, [
      '- [a-rule](active/a-rule.md): adding or changing a test.',
      '- [b-rule](active/b-rule.md): editing a migration file [gate: no-sweep]',
    ])
    assert.match(text, /^# Active rules\n\nGenerated by caselaw/, 'the header says it is generated')
    assert.match(text, /open a rule's file \(the link\) only when its Trigger matches/, 'and how to open a rule')
    const again = await syncRuleIndex(root)
    assert.equal(again.changed, false, 'a second run changes nothing')
    assert.equal(await read('docs/rules/INDEX.md'), text)
  })

  test('POSITIVE CONTROL: candidates and proposals are not listed; an empty active/ says so', async () => {
    await put('docs/rules/candidates/cand.md', rule('cand', 'renaming a thing'))
    await put('docs/rules/proposed/prop.md', rule('prop', 'sending a message'))
    await put('docs/rules/active/WHY-THIS-IS-EMPTY.md', '# why\n')
    await syncRuleIndex(root)
    const text = await read('docs/rules/INDEX.md')
    assert.doesNotMatch(text, /cand|prop|renaming|sending/)
    assert.match(text, /No active rules\./)
  })

  test('POSITIVE CONTROL: ratify and demote regenerate it; a stale index is reported, a missing one too', async () => {
    await put('docs/rules/proposed/new-rule.md', rule('new-rule', 'publishing a release'))
    await put('docs/rules/active/old-rule.md', rule('old-rule', 'adding a test'))
    await syncRuleIndex(root)
    assert.equal((await ruleIndexState(root)).state, 'ok')

    await ratify(root, 'new-rule', { interactive: true, ratifiedBy: 't', resolveRef: false })
    assert.match(await read('docs/rules/INDEX.md'), /\[new-rule\]\(active\/new-rule\.md\): publishing a release/)
    assert.equal((await ruleIndexState(root)).state, 'ok', 'ratify left it current')

    await demote(root, 'old-rule', { interactive: true, reason: 'not needed' })
    assert.doesNotMatch(await read('docs/rules/INDEX.md'), /old-rule/)
    assert.equal((await ruleIndexState(root)).state, 'ok', 'demote left it current')

    await put('docs/rules/active/sneaky.md', rule('sneaky', 'a hand-copied rule'))
    assert.equal((await ruleIndexState(root)).state, 'stale', 'a rule dropped into active/ by hand leaves the index stale')
    await rm(join(root, 'docs/rules/INDEX.md'))
    assert.equal((await ruleIndexState(root)).state, 'missing')
  })

  test('POSITIVE CONTROL: the audit reports a stale or missing index; a current one is silent', () => {
    const run = (ruleIndex) => runChecks({ ruleIndex, rules: { active: [], proposed: [], candidates: [] } }, { only: ['rule-index-current'] }).findings
    assert.deepEqual(run({ state: 'ok', path: 'docs/rules/INDEX.md' }), [])
    assert.deepEqual(run(null), [], 'no install, nothing to report')
    const stale = run({ state: 'stale', path: 'docs/rules/INDEX.md' })
    assert.equal(stale.length, 1)
    assert.match(stale[0].message, /out of date with the rules in active\//)
    assert.match(run({ state: 'missing', path: 'docs/rules/INDEX.md' })[0].message, /missing/)
  })

  test('POSITIVE CONTROL (end to end): init writes it, check fails on a stale one, upgrade fixes it, audit names it', async () => {
    await put('README.md', '# P\n')
    execFileSync('git', ['add', '-A'], { cwd: root })
    execFileSync('git', ['commit', '-qm', 'x'], { cwd: root })
    const init = await cli(['init', '--yes'], { cwd: root, input: '2\np\nTap through it on a phone.\nRun the suite.\n' })
    assert.equal(init.code, 0, init.out)
    assert.ok(await exists('docs/rules/INDEX.md'), 'init writes the index')
    assert.equal((await cli(['check'], { cwd: root })).code, 0)

    await put('docs/rules/active/hand-added.md', rule('hand-added', 'deleting a user account'))
    const stale = await cli(['check'], { cwd: root })
    assert.equal(stale.code, 1, stale.out)
    assert.match(stale.out, /STALE\s+docs\/rules\/INDEX\.md/)
    const audit = await cli(['audit'], { cwd: root })
    assert.match(audit.out, /rule-index-current|INDEX\.md is out of date/)

    const up = await cli(['upgrade', '--yes'], { cwd: root })
    assert.equal(up.code, 0, up.out)
    assert.match(await read('docs/rules/INDEX.md'), /hand-added/)
    assert.equal((await cli(['check'], { cwd: root })).code, 0, 'upgrade fixed it')

    await rm(join(root, 'docs/rules/INDEX.md'))
    const missing = await cli(['check'], { cwd: root })
    assert.equal(missing.code, 1)
    assert.match(missing.out, /MISSING\s+docs\/rules\/INDEX\.md/)
    assert.equal((await cli(['upgrade', '--yes'], { cwd: root })).code, 0)
    assert.ok(await exists('docs/rules/INDEX.md'), 'upgrade restores a missing index even when nothing else changed')
  })
})

describe('the pointer', () => {
  test('POSITIVE CONTROL: it sends the agent to the index, then to a rule only when its Trigger matches; the authority split and close-out lines stay', () => {
    const text = pointerLines('docs').map((l) => l.text).join('\n')
    assert.match(text, /docs\/rules\/INDEX\.md/)
    assert.match(text, /only when its Trigger matches/)
    assert.doesNotMatch(text, /scan it and load every rule/, 'the old instruction made an agent open every file')
    assert.match(text, /docs\/authority-split\.md.*Read it first/)
    assert.match(text, /docs\/close-out\.md/)
    assert.match(pointerLines('governance').map((l) => l.text).join('\n'), /governance\/rules\/INDEX\.md/, 'it follows a relocated doctrine directory')
  })
})

describe('an install made before the index', () => {
  test('POSITIVE CONTROL: upgrade replaces the unmodified old pointer with the new one and writes the index; an edited pointer is left alone', async () => {
    await put('README.md', '# P\n')
    execFileSync('git', ['add', '-A'], { cwd: root })
    execFileSync('git', ['commit', '-qm', 'x'], { cwd: root })
    assert.equal((await cli(['init', '--yes'], { cwd: root, input: '2\np\nTap.\nRun.\n' })).code, 0)
    const OLD = '- `docs/rules/active/` — case law. At session start, scan it and load every rule whose Trigger matches this turn. Rules are trigger-scoped, never ambient.'
    const current = await read('AGENTS.md')
    const interior = /<!-- caselaw:begin[^>]*-->\n([\s\S]*?)\n<!-- caselaw:end/.exec(current)[1]
    await writeFile(join(root, 'AGENTS.md'), upsert('', { id: 'pointer', version: 1, filePath: 'AGENTS.md', body: interior.replace(/- `docs\/rules\/INDEX\.md`.*/, OLD) }).text, 'utf8')
    await rm(join(root, 'docs/rules/INDEX.md'))
    assert.match(await read('AGENTS.md'), /scan it and load every rule/)

    const up = await cli(['upgrade', '--yes'], { cwd: root })
    assert.equal(up.code, 0, up.out)
    const after = await read('AGENTS.md')
    assert.doesNotMatch(after, /scan it and load every rule/)
    assert.match(after, /docs\/rules\/INDEX\.md/)
    assert.ok(await exists('docs/rules/INDEX.md'))

    // A pointer a human edited is theirs: upgrade leaves it, and says so.
    await writeFile(join(root, 'AGENTS.md'), after.replace('Never ambient.', 'Never ambient. (my edit)'), 'utf8')
    await cli(['upgrade', '--yes'], { cwd: root })
    assert.match(await read('AGENTS.md'), /\(my edit\)/)
  })
})

describe('rules --for', () => {
  const D2 = async () => {
    const doc = emptyAnswers({ templateVersion: '1.2', project: { name: 'P' } })
    doc.generatedAt = '2026-10-30T00:00:00.000Z'
    doc.answers['harness.defaults'] = ['D2', 'D3']
    doc.harness = { since: '2026-10-30' }
    const artifacts = await buildArtifacts({ doc, detected: { agentConfig: { claudeMd: true }, commands: {}, deploySurface: [] } })
    for (const a of artifacts.filter((x) => x.path.startsWith('docs/rules/active/'))) await put(a.path, a.body)
  }
  const run = async (args) => {
    const lines = []
    const code = await listRulesCmd(args, { root, say: (s) => lines.push(s) })
    return { code, text: lines.join('\n') }
  }

  test('keywords are derived from the path, and only when the path says what kind of work it is', () => {
    assert.ok(pathKeywords('tests/test_x.py').includes('test'))
    assert.ok(pathKeywords('src/foo.test.js').includes('test'))
    assert.ok(pathKeywords('docs/guide.md').includes('doc'))
    assert.ok(pathKeywords('README.md').includes('readme'))
    assert.ok(pathKeywords('package.json').includes('dependenc') && pathKeywords('package.json').includes('publish'))
    assert.ok(pathKeywords('.github/workflows/ci.yml').includes('ci'))
    assert.ok(pathKeywords('db/migrations/001_init.sql').includes('migration'))
    assert.deepEqual(pathKeywords('src/render/engine.js'), [], 'an ordinary source path asserts nothing')
    assert.deepEqual(pathKeywords('assets/logo.png'), [])
  })

  test('POSITIVE CONTROL: a test-file path selects seen-to-fail, and says why; an unrelated path selects nothing', async () => {
    await D2()
    const hit = await run({ opt: { for: 'tests/test_x.py' } })
    assert.match(hit.text, /- seen-to-fail:/)
    assert.match(hit.text, /matched tests\/test_x\.py: a test path, and the Trigger says "adding or changing a test"/)
    const miss = await run({ opt: { for: 'src/render/engine.js' } })
    assert.match(miss.text, /No active rules triggered for: src\/render\/engine\.js/)
    assert.doesNotMatch(miss.text, /seen-to-fail/)
  })

  test('POSITIVE CONTROL: several paths, space separated (extra arguments) or in a comma list, are all matched', async () => {
    await put('docs/rules/active/docs-rule.md', rule('docs-rule', 'editing a README or other documentation'))
    await put('docs/rules/active/test-rule.md', rule('test-rule', 'adding or changing a test'))
    for (const args of [
      { opt: { for: 'tests/a.test.js' }, paths: ['README.md'] },
      { opt: { for: 'tests/a.test.js,README.md' } },
      { opt: {}, paths: ['tests/a.test.js', 'README.md'] },
    ]) {
      const r = await run(args)
      assert.match(r.text, /- docs-rule:/, JSON.stringify(args))
      assert.match(r.text, /- test-rule:/, JSON.stringify(args))
    }
    const one = await run({ opt: { for: 'README.md' } })
    assert.doesNotMatch(one.text, /test-rule/, 'the test rule does not fire on a README')
  })

  test('POSITIVE CONTROL: a path the Trigger names still matches by path, and keywords never widen to ordinary source', async () => {
    await put('docs/rules/active/cli-rule.md', rule('cli-rule', 'editing `src/commands/rule.js`'))
    const hit = await run({ opt: { for: 'src/commands/rule.js' } })
    assert.match(hit.text, /matched src\/commands\/rule\.js: the Trigger names this path/)
    assert.equal(selectTriggeredRules([{ name: 'x', trigger: 'adding a test', rule: 'y' }], ['src/render/engine.js']).length, 0)
    assert.deepEqual(explainTriggerMatch('adding a test', 'src/render/engine.js'), [])
    assert.equal(explainTriggerMatch('ADDING A TEST', 'tests/a.py')[0].via, 'keyword', 'case-insensitive')
  })

  test('POSITIVE CONTROL: the CLI takes a second path without treating it as the directory (it crashed with ENOTDIR)', async () => {
    await put('README.md', '# P\n')
    execFileSync('git', ['add', '-A'], { cwd: root })
    execFileSync('git', ['commit', '-qm', 'x'], { cwd: root })
    assert.equal((await cli(['init', '--yes'], { cwd: root, input: '2\np\nTap.\nRun.\n' })).code, 0)
    await put('docs/rules/active/docs-rule.md', rule('docs-rule', 'editing a README or other documentation'))
    await syncRuleIndex(root)
    const r = await cli(['rules', '--for', 'index.js', 'README.md'], { cwd: root })
    assert.equal(r.code, 0, r.out)
    assert.doesNotMatch(r.out, /ENOTDIR|failed/)
    assert.match(r.out, /- docs-rule:/)
    const comma = await cli(['rules', '--for', 'index.js,README.md'], { cwd: root })
    assert.match(comma.out, /- docs-rule:/)
    const withDir = await cli(['rules', root, '--for', 'README.md'], { cwd: tmpdir() })
    assert.match(withDir.out, /- docs-rule:/, 'a leading directory that holds an install is still the project directory')
  })
})

describe('shipped rule text', () => {
  test('POSITIVE CONTROL: a rule that names a private project, a ledger id, or runs long is refused by the check', () => {
    assert.throws(() => assertStrangerReadable('**Precedent:** in Kabu, 2026-01-01.', 'x'), /private project/)
    assert.throws(() => assertStrangerReadable('DEF-521 happened.', 'x'), /private project/)
    assert.throws(() => assertStrangerReadable('word '.repeat(200), 'x'), /words/)
    assertStrangerReadable('a plain sentence about a check that never ran (2026-09-25).', 'x')
  })

  test('the default rule file for a stranger parses to its Trigger, Rule and a short Precedent', async () => {
    await D2Like()
    const parsed = parseRule(await read('docs/rules/active/seen-to-fail.md'))
    assert.match(parsed.trigger, /adding or changing a test/)
    assert.ok(parsed.precedent.split(/\s+/).length <= 30, 'the loaded precedent is one sentence and a link')
  })

  async function D2Like() {
    const doc = emptyAnswers({ templateVersion: '1.2', project: { name: 'P' } })
    doc.generatedAt = '2026-10-30T00:00:00.000Z'
    doc.answers['harness.defaults'] = ['D2']
    doc.harness = { since: '2026-10-30' }
    const artifacts = await buildArtifacts({ doc, detected: { agentConfig: { claudeMd: true }, commands: {}, deploySurface: [] } })
    await put('docs/rules/active/seen-to-fail.md', artifacts.find((a) => a.path.endsWith('seen-to-fail.md')).body)
    assert.ok(artifacts.some((a) => a.path === 'docs/rules/PRECEDENT.md'), 'the precedent file ships once, beside the rules')
  }
})

describe('keyword matching is about the kind of work (0.5.1)', () => {
  test('POSITIVE CONTROL: a test path loads the rule about editing tests, not the one about running "build then test"', async () => {
    const { explainTriggerMatch } = await import('../../src/core/rules.js')
    assert.ok(explainTriggerMatch('adding or changing a test, check, gate or script that decides pass or fail', 'tests/test_x.py').length)
    assert.equal(explainTriggerMatch('running steps where one depends on the one before: build then test, test then commit', 'tests/test_x.py').length, 0)
    assert.equal(explainTriggerMatch('reporting the result of any check, test run, audit or review', 'tests/test_x.py').length, 0)
  })
  test('POSITIVE CONTROL: a paid-API client file loads the spend rule; an ordinary file does not', async () => {
    const { explainTriggerMatch } = await import('../../src/core/rules.js')
    const spend = 'a call to a paid or metered API: a model, a scraper, a media generator, anything billed per call or per unit.'
    assert.ok(explainTriggerMatch(spend, 'Sources/Reprompt/GroqClient.swift').length)
    assert.equal(explainTriggerMatch(spend, 'Sources/Reprompt/SettingsView.swift').length, 0)
  })
})
